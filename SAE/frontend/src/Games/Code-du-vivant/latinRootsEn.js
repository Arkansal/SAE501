export const breakdownScientificName = (scientificName) => {
  if (!scientificName) return [];
  const name = scientificName.toLowerCase();
  const sortedRoots = Object.keys(latinRootsEn).sort((a, b) => b.length - a.length);
  
  const decomposeSegment = (segment) => {
    if (!segment || !segment.trim()) return [];
    for (const root of sortedRoots) {
      if (segment.includes(root)) {
        const index = segment.indexOf(root);
        const result = [];
        if (index > 0) {
          const before = segment.substring(0, index);
          result.push(...decomposeSegment(before));
        }
        result.push({ part: root, meaning: latinRootsEn[root] });
        if (index + root.length < segment.length) {
          const after = segment.substring(index + root.length);
          result.push(...decomposeSegment(after));
        }
        return result;
      }
    }
    return segment.trim() ? [{ part: segment.trim(), meaning: '(Name element)' }] : [];
  };
  
  const result = decomposeSegment(name);
  if (result.length === 0 || result.every(p => p.meaning === '(Name element)')) {
    return [{ part: scientificName, meaning: 'Scientific name' }];
  }
  return result;
};